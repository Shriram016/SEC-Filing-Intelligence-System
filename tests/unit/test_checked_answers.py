import json
from typing import Any

import pytest

from filing_rag.engine.answer import Calculation, Claim, WriterOutput
from filing_rag.engine.calculator import CalcError, Quantity, calculate
from filing_rag.engine.checked import CheckedAnswerer
from filing_rag.engine.checks import Failure, check_claim, quote_in_text
from filing_rag.engine.final import Status, decide, fmt_value
from filing_rag.llm.fake import FakeLLM
from filing_rag.search.searcher import Hit

CASH_FLOW = (
    "CONDENSED CONSOLIDATED STATEMENTS OF CASH FLOWS (Unaudited)\n(In millions)\n"
    "Cash generated by operating activities          88,945         98,024\n"
    "Payments for acquisition of property, plant and equipment     (8,796)    (7,419)\n"
    "Apple’s net sales — Services            85,200"
)
TEXT = "Total net sales decreased 3% or $11.0 billion during the first nine months of 2023."


def hit(text: str, page: int = 8, doc: str = "APPLE_2023Q3_10Q") -> Hit:
    return Hit(0.9, {
        "chunk_id": f"{doc}-{page}", "doc_name": doc, "page": page, "page_end": page,
        "text": text, "company": "Apple", "doc_type": "10-Q", "period_end": "2023-07-01",
        "fiscal_year": 2023,
    })  # fmt: skip


HITS = [hit(TEXT, 20), hit(CASH_FLOW, 8)]


def claim(cid: str, quote: str, value: float | None, extract: int = 2, **kw: Any) -> Claim:
    unit = kw.pop("unit", "USD million" if value is not None else None)
    return Claim(id=cid, label=kw.pop("label", f"fact {cid}"), extract=extract, quote=quote,
                 value=value, unit=unit, period="nine months ended July 1, 2023", **kw)  # fmt: skip


OCF = claim("c1", "Cash generated by operating activities 88,945", 88945, label="operating cash")
CAPEX = claim(
    "c2", "Payments for acquisition of property, plant and equipment (8,796)", -8796,
    label="capex",
)  # fmt: skip


# ---------- quote check ----------


def test_a_good_claim_passes() -> None:
    assert check_claim(OCF, HITS).ok


def test_table_spaces_case_curly_quotes_and_dashes_are_forgiven() -> None:
    assert quote_in_text("cash GENERATED by operating activities 88,945 98,024", CASH_FLOW)
    assert check_claim(claim("c3", "Apple's net sales - Services 85,200", 85200), HITS).ok


def test_a_negative_in_parentheses_matches() -> None:
    assert check_claim(CAPEX, HITS).ok


@pytest.mark.parametrize(
    ("c", "failure"),
    [
        (claim("c1", "Cash generated by operating activities 88,945", 88945, extract=3),
         Failure.BAD_EXTRACT),
        (claim("c1", "Cash generated by operating activities 88,945", 88945, extract=1),
         Failure.QUOTE_NOT_FOUND),  # right text, wrong extract
        (claim("c1", "Cash generated by investing activities 88,945", 88945),
         Failure.QUOTE_NOT_FOUND),  # a changed word
        (claim("c1", "Cash generated by operating activities 88,945", 98945),
         Failure.VALUE_NOT_IN_QUOTE),  # value not in the quote
        (claim("c1", "Cash generated by operating activities 88,945", 88.945),
         Failure.VALUE_NOT_IN_QUOTE),  # scale changed by the model
        (claim("c1", "88,945", 88945), Failure.QUOTE_TOO_SHORT),
        (claim("c1", "88,945 98,024", 88945), Failure.QUOTE_TOO_SHORT),  # no words
    ],
)  # fmt: skip
def test_bad_claims_fail_with_a_reason(c: Claim, failure: Failure) -> None:
    assert check_claim(c, HITS).failure == failure


def test_a_statement_without_a_value_needs_only_the_quote() -> None:
    c = claim("c1", "Total net sales decreased 3% or $11.0 billion", None, extract=1)
    assert check_claim(c, HITS).ok


def test_the_value_must_keep_the_printed_scale() -> None:
    printed = claim("c1", "decreased 3% or $11.0 billion during", 11.0, extract=1,
                    unit="USD billion")  # fmt: skip
    assert check_claim(printed, HITS).ok
    rescaled = claim("c1", "decreased 3% or $11.0 billion during", 11000, extract=1)
    assert check_claim(rescaled, HITS).failure == Failure.VALUE_NOT_IN_QUOTE


# ---------- calculator ----------


def q(v: float, unit: str | None = "USD million") -> Quantity:
    return Quantity(v, unit)


def test_calculator_ops() -> None:
    assert calculate("add", [q(1), q(2), q(3)]).value == 6
    r = calculate("subtract", [q(88945), q(8796)])
    assert r.value == 80149 and r.unit == "USD million" and r.formula == "88,945 - 8,796"
    assert calculate("divide", [q(10), q(4)]).value == 2.5
    m = calculate("ratio_pct", [q(2474), q(5762)])
    assert m.unit == "%" and m.value == pytest.approx(42.94, abs=0.01)
    c = calculate("pct_change", [q(200), q(150)])
    assert c.value == pytest.approx(-25.0) and c.unit == "%"


def test_a_negative_input_is_shown_in_parentheses() -> None:
    r = calculate("add", [q(88945), q(-8796)])
    assert r.value == 80149 and r.formula == "88,945 + (-8,796)"


def test_scales_are_converted() -> None:
    r = calculate("subtract", [q(2.0, "USD billion"), q(500.0, "USD million")])
    assert r.value == pytest.approx(1.5) and r.unit == "USD billion"
    assert calculate("ratio_pct", [q(500, "USD thousand"), q(1, "USD million")]).value == 50


def test_percent_points_subtract() -> None:
    assert calculate("subtract", [q(42.9, "%"), q(40.4, "%")]).value == pytest.approx(2.5)


@pytest.mark.parametrize(
    ("op", "inputs"),
    [
        ("subtract", [q(10), q(5, "%")]),  # USD minus percent
        ("ratio_pct", [q(10), q(5, "shares")]),  # USD over a count
        ("divide", [q(10), q(0)]),
        ("pct_change", [q(0), q(5)]),
        ("add", [q(1)]),
        ("subtract", [q(1), q(2), q(3)]),
    ],
)
def test_calculator_refuses_bad_input(op: str, inputs: list[Quantity]) -> None:
    with pytest.raises(CalcError):
        calculate(op, inputs)


def test_fmt_value() -> None:
    assert fmt_value(80149, "USD million") == "$80,149 million"
    assert fmt_value(-8796, "USD million") == "-$8,796 million"
    assert fmt_value(42.944, "%") == "42.9%"
    assert fmt_value(1234.5, "shares") == "1,234.5 shares"


# ---------- final rule ----------


def fcf(answer: str = "Free cash flow was {k1}.", **kw: Any) -> WriterOutput:
    calc = Calculation(id="k1", op="subtract", inputs=["c1", "c2"], label="free cash flow",
                       unit="USD million")  # fmt: skip
    base: dict[str, Any] = {"found": True, "claims": [OCF, claim(
        "c2", "Payments for acquisition of property, plant and equipment (8,796)", 8796,
        label="capex")], "calculations": [calc], "main": "k1", "answer": answer}  # fmt: skip
    return WriterOutput(**(base | kw))


def test_full_answer_fills_the_placeholders_with_checked_values() -> None:
    a = decide(fcf(), HITS)
    assert a.status == Status.ANSWER
    assert a.text.startswith("Free cash flow was $80,149 million.")
    assert "free cash flow = 88,945 - 8,796 = $80,149 million" in a.text
    assert "Source: Apple 10-Q (period ended 01 Jul 2023)" in a.text
    assert a.main_value == 80149 and a.main_unit == "USD million"
    assert [(s.doc_name, s.page) for s in a.sources] == [("APPLE_2023Q3_10Q", 8)]
    b = a.to_baseline()
    assert b.found and b.value == 80149


def test_a_number_written_by_the_model_is_never_shown() -> None:
    a = decide(fcf(answer="Free cash flow was $80,150 million in fiscal 2023."), HITS)
    assert a.status == Status.ANSWER
    assert "80,150" not in a.text
    assert a.text.startswith("free cash flow: $80,149 million.")
    assert not a.sentence_used and "80,150" in a.model_sentence  # kept for the logs
    assert decide(fcf(), HITS).sentence_used


@pytest.mark.parametrize(
    "answer",
    [
        "Free cash flow was {k1} million USD.",
        "Free cash flow was {k1} million.",
        "Free cash flow was ${k1}.",
        "Free cash flow was {k1}%.",
        "Free cash flow was {k1} dollars.",
    ],
)
def test_a_unit_next_to_a_placeholder_is_not_doubled(answer: str) -> None:
    a = decide(fcf(answer=answer), HITS)
    assert a.status == Status.ANSWER and not a.sentence_used
    assert "million million" not in a.text and "$$" not in a.text
    assert a.text.startswith("free cash flow: $80,149 million.")


def test_a_unit_word_away_from_a_placeholder_is_allowed() -> None:
    a = decide(fcf(answer="In USD, free cash flow was {k1} for the nine months."), HITS)
    assert a.sentence_used


def test_years_and_dates_in_the_sentence_are_allowed() -> None:
    a = decide(fcf(answer="For the nine months ended July 1, 2023 (Q3 of fiscal 2023), "
                          "free cash flow was {k1} (FY2023, FY 23)."), HITS)  # fmt: skip
    assert a.text.startswith("For the nine months ended July 1, 2023 (Q3 of fiscal 2023), free")
    assert "$80,149 million (FY2023, FY 23)." in a.text


def test_a_failed_input_makes_a_partial_answer_without_a_main_value() -> None:
    bad = claim("c2", "Payments for acquisition of property, plant and equipment (9,999)", 9999,
                label="capex")  # fmt: skip
    a = decide(fcf(claims=[OCF, bad]), HITS)
    assert a.status == Status.PARTIAL
    assert a.main_value is None and not a.to_baseline().value
    assert "Checked facts: operating cash: $88,945 million." in a.text
    assert "Could not check: capex, free cash flow." in a.text
    assert a.failures == {"quote_not_found": 1, "calc_error": 1}


def test_found_false_or_no_passed_claim_is_a_refusal() -> None:
    a = decide(WriterOutput(found=False, answer="Not in the extracts."), HITS)
    assert a.status == Status.REFUSED and not a.to_baseline().found
    bad = claim("c1", "Cash generated by operating activities 1,234", 1234)
    r = decide(WriterOutput(found=True, claims=[bad], main="c1", answer="It was {c1}."), HITS)
    assert r.status == Status.REFUSED and "1,234" not in r.text


def test_a_text_answer_without_a_main_value() -> None:
    c = claim("c1", "Total net sales decreased 3% or $11.0 billion", None, extract=1,
              label="net sales trend")  # fmt: skip
    out = WriterOutput(found=True, claims=[c], main=None, answer="Net sales went down.")
    a = decide(out, HITS)
    assert a.status == Status.ANSWER and a.main_value is None
    assert a.text.startswith("Net sales went down.")


def test_an_unknown_placeholder_is_not_trusted() -> None:
    a = decide(fcf(answer="Free cash flow was {k9}."), HITS)
    assert a.status == Status.PARTIAL and "{k9}" not in a.text


# ---------- writer call ----------


def writer_json(out: WriterOutput) -> str:
    return json.dumps(out.model_dump())


def test_broken_json_gets_one_retry() -> None:
    llm = FakeLLM(["not json", writer_json(fcf())])
    r = CheckedAnswerer(llm).answer("FCF?", HITS)
    assert len(llm.calls) == 2 and r.error is None
    assert r.checked is not None and r.checked.status == Status.ANSWER
    assert r.answer is not None and r.answer.value == 80149


def test_twice_broken_json_is_a_clear_error() -> None:
    r = CheckedAnswerer(FakeLLM(["{", "{"])).answer("FCF?", HITS)
    assert r.answer is None and r.error and "invalid JSON" in r.error


def test_a_failed_check_makes_no_second_call() -> None:
    bad = claim("c1", "Cash generated by operating activities 1,234", 1234)
    out = WriterOutput(found=True, claims=[bad], main="c1", answer="It was {c1}.")
    llm = FakeLLM([writer_json(out)])
    r = CheckedAnswerer(llm).answer("OCF?", HITS)
    assert len(llm.calls) == 1 and r.checked is not None
    assert r.checked.status == Status.REFUSED


def test_duplicate_ids_are_broken_json() -> None:
    dup = WriterOutput(found=True, claims=[OCF, OCF], main="c1", answer="{c1}")
    r = CheckedAnswerer(FakeLLM([writer_json(dup), writer_json(dup)])).answer("x", HITS)
    assert r.error and "duplicate" in r.error


def test_the_prompt_numbers_the_extracts() -> None:
    llm = FakeLLM([writer_json(fcf())])
    CheckedAnswerer(llm).answer("FCF?", HITS)
    user = llm.calls[0]["user"]
    assert "[1] APPLE_2023Q3_10Q, page 20" in user and "[2] APPLE_2023Q3_10Q, page 8" in user
    assert "Question: FCF?" in user
