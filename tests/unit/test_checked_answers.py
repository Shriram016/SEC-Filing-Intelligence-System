CASH_FLOW = (
    "CONDENSED CONSOLIDATED STATEMENTS OF CASH FLOWS (Unaudited)\n(In millions)\n"
    "Cash generated by operating activities          88,945         98,024\n"
    "Payments for acquisition of property, plant and equipment     (8,796)    (7,419)\n"
    "Apple’s net sales — Services            85,200"
)
TEXT = "Total net sales decreased 3% or $11.0 billion during the first nine months of 2023."


def hit(text: str, page: int = 8, doc: str = "APPLE_2023Q3_10Q") -> Hit:
    return Hit(0.9, {
        "chunk_id": f"{doc}-{page}", "doc_name": doc, "page": page, "page_end": page,
        "text": text, "company": "Apple", "doc_type": "10-Q", "period_end": "2023-07-01",
        "fiscal_year": 2023,
    })  # fmt: skip


HITS = [hit(TEXT, 20), hit(CASH_FLOW, 8)]


def ref(i: str) -> CalcInput:
    return CalcInput(ref=i)


def const(x: float) -> CalcInput:
    return CalcInput(const=x)


def claim(cid: str, quote: str, value: float | None, extract: int = 2, **kw: Any) -> Claim:
    unit = kw.pop("unit", "USD million" if value is not None else None)
    return Claim(id=cid, label=kw.pop("label", f"fact {cid}"), extract=extract, quote=quote,
                 value=value, unit=unit, period="nine months ended July 1, 2023", **kw)  # fmt: skip


OCF = claim("c1", "Cash generated by operating activities 88,945", 88945, label="operating cash")
CAPEX = claim(
    "c2", "Payments for acquisition of property, plant and equipment (8,796)", -8796,
    label="capex",
)  # fmt: skip


